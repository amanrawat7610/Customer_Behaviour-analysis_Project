-- 7. Do subscribed customers spend more? Compare average spend and total revenue between subscription statuses
SELECT 
    subscription_status, 
    COUNT(customer_id) AS users, 
    ROUND(AVG(purchase_amount), 2) AS avg_revenue, 
    ROUND(SUM(purchase_amount), 2) AS total_revenue
FROM sales_data
