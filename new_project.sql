-- 4. Which customer used a discount but still spent more than the average purchase amount?
SELECT 
    customer_id, 
    purchase_amount, 
    discount_applied
FROM sales_data
WHERE discount_applied = 'Yes' 
  AND purchase_amount > (SELECT AVG(purchase_amount) FROM sales_data)
LIMIT 10;

-- Business Problem: Company cannot identify high-spending customers who are also discount users.


-- 5. Which are the top/bottom 5 products with the highest/lowest average review rating?

-- Top 5 products
SELECT 
    item_purchased, 
    ROUND(AVG(review_rating), 2) AS Avg_ratings
FROM sales_data
GROUP BY item_purchased
ORDER BY Avg_ratings DESC
LIMIT 5;

-- Bottom 5 products
SELECT 
    item_purchased, 
    ROUND(AVG(review_rating), 2) AS Avg_ratings
FROM sales_data
GROUP BY item_purchased
ORDER BY Avg_ratings ASC
LIMIT 5;


